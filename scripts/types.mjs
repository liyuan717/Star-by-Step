import { PGlite } from "@electric-sql/pglite";
import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
const db = new PGlite();
await db.exec(
  `create role anon;create role authenticated;create role service_role;create schema auth;create table auth.users(id uuid primary key);create function auth.uid() returns uuid language sql as $$select null::uuid$$;`,
);
for (const f of (await readdir("supabase/migrations")).sort())
  if (!f.includes("storage"))
    await db.exec(await readFile(`supabase/migrations/${f}`, "utf8"));
const { rows } = await db.query(
  "select table_name,column_name,data_type,is_nullable from information_schema.columns where table_schema='public' order by table_name,ordinal_position",
);
const tables = {};
for (const r of rows) {
  const t = (tables[r.table_name] ||= {});
  t[r.column_name] =
    (["integer", "bigint", "smallint", "numeric"].includes(r.data_type)
      ? "number"
      : r.data_type === "boolean"
        ? "boolean"
        : r.data_type === "jsonb"
          ? "Json"
          : "string") + (r.is_nullable === "YES" ? " | null" : "");
}
let text =
  "// Generated by scripts/types.mjs from migrated PostgreSQL information_schema.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport interface Rows {\n";
for (const [t, cols] of Object.entries(tables)) {
  text += `  ${t}: {\n`;
  for (const [k, v] of Object.entries(cols)) text += `    ${k}: ${v};\n`;
  text += "  };\n";
}
text += "}\nexport type Row<T extends keyof Rows> = Rows[T];\n";
await mkdir("src/types", { recursive: true });
await writeFile("src/types/database.generated.ts", text);
await db.close();
console.log("Generated table row types from migrated schema");
